const header = document.querySelector("[data-header]");
let currentLanguage = "pl";
let visibleProducts = products;
let activeProductIndex = -1;

function preferredLanguage() {
  const query = new URLSearchParams(window.location.search).get("lang");
  const saved = localStorage.getItem("niedzwieccy-language");
  const browser = navigator.language.slice(0, 2).toLowerCase();
  return [query, saved, browser, "pl"].find((code) => supportedLanguages.includes(code));
}

function normalize(value) {
  return value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
}

function catalogImage(product) {
  return `assets/catalog/catalog-${String(product.page).padStart(2, "0")}.webp`;
}

function setHomeLinks(lang) {
  document.querySelectorAll("[data-home-link]").forEach((link) => {
    if (!link.dataset.baseHref) link.dataset.baseHref = link.getAttribute("href");
    const [path, hash = ""] = link.dataset.baseHref.split("#");
    link.href = `${path}?lang=${lang}${hash ? `#${hash}` : ""}`;
  });
}

function applyLanguage(lang, updateUrl = false) {
  currentLanguage = supportedLanguages.includes(lang) ? lang : "pl";
  const copy = catalogTranslations[currentLanguage];
  document.documentElement.lang = currentLanguage;
  document.title = copy.metaTitle;
  document.querySelector('meta[name="description"]').content = copy.metaDescription;
  document.querySelector('meta[property="og:title"]').content = copy.metaTitle;
  document.querySelector('meta[property="og:description"]').content = copy.metaDescription;
  document.querySelectorAll("[data-catalog-i18n]").forEach((element) => {
    const value = copy[element.dataset.catalogI18n];
    if (value) element.textContent = value;
  });
  search.placeholder = copy.searchPlaceholder;
  languageSelector.value = currentLanguage;
  languageSelector.setAttribute("aria-label", copy.language);
  document.querySelector("[data-dialog-close]").setAttribute("aria-label", copy.closeLabel);
  document.querySelector("[data-dialog-prev]").setAttribute("aria-label", copy.prevLabel);
  document.querySelector("[data-dialog-next]").setAttribute("aria-label", copy.nextLabel);
  setHomeLinks(currentLanguage);
  localStorage.setItem("niedzwieccy-language", currentLanguage);
  if (updateUrl) {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", currentLanguage);
    history.replaceState({}, "", url);
  }
  renderProducts(search.value);
}

function makeCard(product) {
  const copy = catalogTranslations[currentLanguage];
  const article = document.createElement("article");
  article.className = "catalog-card";

  const button = document.createElement("button");
  button.className = "catalog-card-button";
  button.type = "button";
  button.setAttribute("aria-label", `${copy.open}: ${product.name} ${product.code}`);
  button.addEventListener("click", () => openProduct(product.id));

  const sheet = document.createElement("span");
  sheet.className = "catalog-card-sheet";
  const image = document.createElement("img");
  image.src = catalogImage(product);
  image.alt = `${product.name} ${product.code}`;
  image.loading = "lazy";
  image.decoding = "async";
  sheet.append(image);

  const meta = document.createElement("span");
  meta.className = "catalog-card-meta";
  const title = document.createElement("h3");
  title.textContent = product.name;
  const code = document.createElement("code");
  code.textContent = product.code;
  meta.append(title, code);

  const action = document.createElement("span");
  action.className = "catalog-card-action";
  action.textContent = `${copy.open} ↗`;
  button.append(sheet, meta, action);
  article.append(button);
  return article;
}

function renderProducts(query = "") {
  const needle = normalize(query.trim());
  visibleProducts = products.filter((product) => normalize(`${product.name} ${product.code} ${product.aliases || ""}`).includes(needle));
  grid.replaceChildren(...visibleProducts.map(makeCard));
  const copy = catalogTranslations[currentLanguage];
  status.textContent = copy.result.replace("{visible}", visibleProducts.length).replace("{total}", products.length);
  empty.hidden = visibleProducts.length !== 0;
}

function openProduct(id) {
  const productIndex = products.findIndex((product) => product.id === id);
  if (productIndex < 0) return;
  activeProductIndex = productIndex;
  const product = products[productIndex];
  dialogImage.src = catalogImage(product);
  dialogImage.alt = `${product.name} ${product.code}`;
  dialogTitle.textContent = product.name;
  dialogCode.textContent = product.code;
  dialogPosition.textContent = `${String(productIndex + 1).padStart(2, "0")} / ${String(products.length).padStart(2, "0")}`;
  dialogContact.href = `mailto:biuro@niedzwieccy.com?subject=${encodeURIComponent(`Zapytanie o model ${product.name} ${product.code}`)}`;
  history.replaceState({}, "", `#${product.id}`);
  if (!dialog.open) dialog.showModal();
}

function changeProduct(step) {
  if (activeProductIndex < 0) return;
  const nextIndex = (activeProductIndex + step + products.length) % products.length;
  openProduct(products[nextIndex].id);
}

function clearProductHash() {
  const url = new URL(window.location.href);
  url.hash = "";
  history.replaceState({}, "", url);
}

languageSelector.addEventListener("change", (event) => applyLanguage(event.target.value, true));
search.addEventListener("input", (event) => renderProducts(event.target.value));
document.querySelector("[data-dialog-close]").addEventListener("click", () => dialog.close());
document.querySelector("[data-dialog-prev]").addEventListener("click", () => changeProduct(-1));
document.querySelector("[data-dialog-next]").addEventListener("click", () => changeProduct(1));
dialog.addEventListener("click", (event) => { if (event.target === dialog) dialog.close(); });
dialog.addEventListener("close", clearProductHash);

menuButton.addEventListener("click", () => {
  const open = menuButton.getAttribute("aria-expanded") === "true";
  menuButton.setAttribute("aria-expanded", String(!open));
  nav.classList.toggle("open", !open);
  document.body.classList.toggle("menu-open", !open);
});
nav.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
  menuButton.setAttribute("aria-expanded", "false");
  nav.classList.remove("open");
  document.body.classList.remove("menu-open");
}));

